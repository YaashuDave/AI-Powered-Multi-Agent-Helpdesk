# monitor.py

import os
import json
from datetime import datetime
from typing import List
from pydantic import BaseModel, Field
from a2a.a2a_protocol import BUS

# Ensure directories exist
os.makedirs("output", exist_ok=True)
os.makedirs("output/logs", exist_ok=True)
os.makedirs("output/tickets", exist_ok=True)

LOG_FILE = "output/logs/run.log"
FINAL_JSON = "output/final.json"
FINAL_MD = "output/final.md"
TICKETS_DIR = "output/tickets"


def log(msg: str):
    ts = datetime.now().strftime("[%Y-%m-%d %H:%M:%S]")
    line = f"{ts} {msg}"

    print(line)

    with open(LOG_FILE, "a", encoding="utf-8") as f:
        f.write(line + "\n")


# ---------- Pydantic Structured Output ----------
class FinalOutput(BaseModel):
    ticket_id: str
    troubleshoot: dict
    escalation: dict
    validation: List[dict] = Field(default_factory=list)
    errors: List[dict] = Field(default_factory=list)
    timestamp: str


def render_markdown(final: FinalOutput) -> str:
    md_lines = [
        "# 📝 Final Support Report",
        f"**Ticket ID:** {final.ticket_id}",
        "",
        f"**Generated At:** {final.timestamp}",
        "",
        "---",
        "",
        "## 🛠 Troubleshooting Results",
        "```json",
        json.dumps(final.troubleshoot, indent=4),
        "```",
        "",
        "## 📊 Escalation Decision",
        "```json",
        json.dumps(final.escalation, indent=4),
        "```",
        "",
        "## ✅ Validation (LangGraph)",
    ]
    if final.validation:
        for v in final.validation:
            status = "PASSED" if v.get("validation", {}).get("passed") else "FAILED"
            md_lines.append(f"- `{v.get('source_type')}`: **{status}**")
    else:
        md_lines.append("_No validation results yet._")

    if final.errors:
        md_lines += ["", "## ⚠️ Agent Errors"]
        md_lines += [f"- `{e.get('agent')}`: {e.get('error')}" for e in final.errors]

    md_lines += ["", "---", "Generated by **AI-Powered Multi-Agent Helpdesk**."]
    return "\n".join(md_lines)


def save(final: FinalOutput):
    data = final.model_dump_json(indent=4)
    md_content = render_markdown(final)

    for path in (FINAL_JSON, os.path.join(TICKETS_DIR, f"{final.ticket_id}.json")):
        with open(path, "w", encoding="utf-8") as f:
            f.write(data)
    for path in (FINAL_MD, os.path.join(TICKETS_DIR, f"{final.ticket_id}.md")):
        with open(path, "w", encoding="utf-8") as f:
            f.write(md_content)

    log(f"Saved JSON → {FINAL_JSON}")
    log(f"Saved Markdown → {FINAL_MD}")


# ---------- MONITOR LOOP ----------
def monitor_loop():
    BUS.register("monitor_agent")
    log("Monitor Agent started. Waiting for messages...")

    # results that arrive before / after the final decision, per ticket
    validations = {}
    errors = {}
    finals = {}

    while True:
        msg = BUS.receive("monitor_agent", timeout=1)
        if not msg:
            continue

        payload = msg.payload
        ticket_id = payload.get("ticket_id") or "unknown"

        if msg.type in ("validation_result", "validation_error"):
            validations.setdefault(ticket_id, []).append(payload)
            log(f"Validation for {ticket_id} ({payload.get('source_type', 'error')})")

        elif msg.type == "agent_error":
            errors.setdefault(ticket_id, []).append(payload)
            log(f"ERROR from {payload.get('agent')} on {ticket_id}: {payload.get('error')}")
            # the pipeline stops here, so report the failure and hand it to a human
            finals.setdefault(ticket_id, FinalOutput(
                ticket_id=ticket_id,
                troubleshoot={},
                escalation={"escalate": True, "reason": "Pipeline error, see errors"},
                timestamp=datetime.now().isoformat()
            ))

        elif msg.type == "final_decision":
            log(f"Monitor received final decision for ticket {ticket_id}")
            finals[ticket_id] = FinalOutput(
                ticket_id=ticket_id,
                troubleshoot=payload["troubleshoot"],
                escalation=payload["escalation"],
                timestamp=datetime.now().isoformat()
            )

        else:
            continue

        # (re)write the report whenever something new arrives for a finished ticket
        final = finals.get(ticket_id)
        if final:
            final.validation = validations.get(ticket_id, [])
            final.errors = errors.get(ticket_id, [])
            save(final)
            if msg.type == "final_decision":
                log("=== END OF WORKFLOW ===\n")
